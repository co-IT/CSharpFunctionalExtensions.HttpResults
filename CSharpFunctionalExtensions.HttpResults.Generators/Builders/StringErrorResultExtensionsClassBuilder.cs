using System.Text;
using CSharpFunctionalExtensions.HttpResults.Generators.Utils;

namespace CSharpFunctionalExtensions.HttpResults.Generators.Builders;

/// <summary>
///   Emits the built-in extension methods for <see cref="CSharpFunctionalExtensions.Result" /> and
///   <see cref="CSharpFunctionalExtensions.Result{T}" /> string errors into the same partial class the
///   handwritten implementations used to live in. The static variants are always emitted; the
///   request-service-aware variants only when a provider implementation was discovered.
/// </summary>
internal sealed class StringErrorResultExtensionsClassBuilder(bool includeContextOverloads)
{
  public string SourceFileName => "StringErrorResultExtensions.g.cs";

  public string Build()
  {
    var sourceBuilder = new StringBuilder();

    sourceBuilder.AppendLine("// <auto-generated/>");
    sourceBuilder.AppendLine();
    sourceBuilder.AppendLine("#nullable enable");
    sourceBuilder.AppendLine();
    sourceBuilder.AppendLine(
      """
      using CSharpFunctionalExtensions;
      using Microsoft.AspNetCore.Http;
      using Microsoft.AspNetCore.Http.HttpResults;
      using Microsoft.AspNetCore.Mvc;
      using Microsoft.Net.Http.Headers;
      using System;
      using System.Collections.Generic;
      using System.IO;
      using System.Text;
      using System.Threading.Tasks;
      """
    );

    if (includeContextOverloads)
      sourceBuilder.AppendLine("using Microsoft.Extensions.DependencyInjection;");

    sourceBuilder.AppendLine();
    sourceBuilder.AppendLine("namespace CSharpFunctionalExtensions.HttpResults.ResultExtensions;");
    sourceBuilder.AppendLine();
    sourceBuilder.AppendLine(
      """
      /// <summary>
      /// Extension methods for <see cref="Result"/> and <see cref="Result{T}"/>
      /// </summary>
      """
    );
    sourceBuilder.AppendLine("public static partial class ResultExtensions {");
    sourceBuilder.AppendLine();

    foreach (var method in HttpResultMethodCatalog.StringErrorMethods)
    {
      sourceBuilder.AppendLine(StringErrorMethodRenderer.GenerateStatic(method));
      sourceBuilder.AppendLine();

      if (includeContextOverloads)
      {
        sourceBuilder.AppendLine(StringErrorMethodRenderer.GenerateWithContext(method));
        sourceBuilder.AppendLine();
      }
    }

    sourceBuilder.AppendLine();
    sourceBuilder.AppendLine("}");

    return sourceBuilder.ToString();
  }
}
