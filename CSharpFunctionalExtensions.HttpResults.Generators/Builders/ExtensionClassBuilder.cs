using System.Text;
using CSharpFunctionalExtensions.HttpResults.Generators.Models;
using CSharpFunctionalExtensions.HttpResults.Generators.Rendering;

namespace CSharpFunctionalExtensions.HttpResults.Generators.Builders;

/// <summary>
///   Base builder for the generated extension-method classes that are emitted per discovered error mapper.
/// </summary>
internal abstract class ExtensionClassBuilder(IReadOnlyList<MapperDescriptor> mapperDescriptors)
{
  public string SourceFileName => $"{ClassName}.g.cs";

  protected abstract string ClassName { get; }
  protected abstract string ClassSummary { get; }
  internal abstract IReadOnlyList<HttpResultMethodDefinition> Methods { get; }

  public string Build()
  {
    var sourceBuilder = new StringBuilder();

    sourceBuilder.AppendLine("// <auto-generated/>");
    sourceBuilder.AppendLine();
    sourceBuilder.AppendLine("#nullable enable");
    sourceBuilder.AppendLine();
    GeneratedSourceUsings.AppendTo(sourceBuilder, mapperDescriptors.Any(info => info.IsServiceMapper));

    sourceBuilder.AppendLine(ClassSummary);

    sourceBuilder.AppendLine($"public static partial class {ClassName} {{");
    sourceBuilder.AppendLine();

    foreach (var mapperDescriptor in mapperDescriptors)
    {
      var context = mapperDescriptor.ToContext();

      foreach (var method in Methods)
      {
        sourceBuilder.AppendLine(CustomErrorMethodRenderer.Generate(context, method));
        sourceBuilder.AppendLine();
      }
    }

    sourceBuilder.AppendLine();
    sourceBuilder.AppendLine("}");

    return sourceBuilder.ToString();
  }
}
