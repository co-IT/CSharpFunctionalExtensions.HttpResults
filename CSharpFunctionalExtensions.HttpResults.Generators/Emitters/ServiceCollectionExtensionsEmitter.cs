using System.Text;
using CSharpFunctionalExtensions.HttpResults.Generators.Analysis;
using CSharpFunctionalExtensions.HttpResults.Generators.Utils;
using Microsoft.CodeAnalysis;

namespace CSharpFunctionalExtensions.HttpResults.Generators.Emitters;

/// <summary>Emits zero-configuration scoped registrations for discovered DI implementations.</summary>
internal static class ServiceCollectionExtensionsEmitter
{
  public const string HintName = "ServiceCollectionExtensions.g.cs";

  public static string Emit(
    Compilation compilation,
    INamedTypeSymbol? provider,
    IReadOnlyList<INamedTypeSymbol> referencedServiceMappers,
    IReadOnlyList<MapperInfo> sourceMappers
  )
  {
    var mapperTypes = sourceMappers
      .Where(info => info.IsServiceMapper)
      .Select(info => info.Symbol)
      .Concat(referencedServiceMappers)
      .Where(symbol => IsValidServiceMapper(symbol, compilation))
      .Distinct(SymbolEqualityComparer.Default)
      .OfType<INamedTypeSymbol>()
      .OrderBy(TypeNameResolver.GetFullyQualifiedTypeName, StringComparer.Ordinal)
      .ToArray();

    var source = new StringBuilder();
    source.AppendLine("// <auto-generated/>");
    source.AppendLine();
    source.AppendLine("#nullable enable");
    source.AppendLine("using Microsoft.Extensions.DependencyInjection;");
    source.AppendLine("using Microsoft.Extensions.DependencyInjection.Extensions;");
    source.AppendLine();
    source.AppendLine("namespace CSharpFunctionalExtensions.HttpResults;");
    source.AppendLine();
    // The helper is emitted into every consuming compilation. Keeping its containing type internal avoids
    // clashes with the same generated helper in referenced projects while the extension remains available
    // everywhere inside the application being compiled.
    source.AppendLine("internal static class GeneratedServiceCollectionExtensions {");
    source.AppendLine(
      "  /// <summary>Registers discovered DI-enabled problem-details and error mappers as scoped services.</summary>"
    );
    source.AppendLine(
      "  public static IServiceCollection AddCSharpFunctionalExtensionsHttpResults(this IServiceCollection services) {"
    );

    if (provider is not null)
      source.AppendLine(
        $"    services.TryAddScoped<global::CSharpFunctionalExtensions.HttpResults.IResultProblemDetailsProvider, {TypeNameResolver.GetFullyQualifiedTypeName(provider)}>();"
      );

    foreach (var mapperType in mapperTypes)
      source.AppendLine($"    services.TryAddScoped<{TypeNameResolver.GetFullyQualifiedTypeName(mapperType)}>();");

    source.AppendLine("    return services;");
    source.AppendLine("  }");
    source.AppendLine("}");
    return source.ToString();
  }

  private static bool IsValidServiceMapper(INamedTypeSymbol type, Compilation compilation) =>
    type.TypeKind == TypeKind.Class
    && !type.IsAbstract
    && !type.IsStatic
    && SymbolAccessibility.IsReferenceable(type, compilation.Assembly)
    && SymbolAccessibility.HasPublicInstanceConstructor(type);
}
