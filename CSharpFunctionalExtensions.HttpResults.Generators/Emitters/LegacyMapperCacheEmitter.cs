using System.Text;
using CSharpFunctionalExtensions.HttpResults.Generators.Utils;

namespace CSharpFunctionalExtensions.HttpResults.Generators.Emitters;

/// <summary>Emits internal singleton instances for valid legacy mappers.</summary>
internal static class LegacyMapperCacheEmitter
{
  public const string HintName = "LegacyErrorMapperCache.g.cs";

  public static string Emit(IReadOnlyList<MapperInfo> mapperInfos)
  {
    var source = new StringBuilder();
    source.AppendLine("// <auto-generated/>");
    source.AppendLine();
    source.AppendLine("#nullable enable");
    source.AppendLine();
    source.AppendLine("internal static class CSharpFunctionalExtensionsHttpResultsLegacyMapperCache {");

    foreach (var mapper in mapperInfos.Where(info => !info.IsServiceMapper))
      source.AppendLine(
        $"    internal static {mapper.MapperInterfaceType} {mapper.LegacyCacheMemberName} {{ get; }} = new {mapper.FullyQualifiedName}();"
      );

    source.AppendLine("}");
    return source.ToString();
  }
}
