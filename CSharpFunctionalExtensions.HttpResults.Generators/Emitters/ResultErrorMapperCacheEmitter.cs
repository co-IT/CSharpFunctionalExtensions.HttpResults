using System.Text;
using CSharpFunctionalExtensions.HttpResults.Generators.Models;

namespace CSharpFunctionalExtensions.HttpResults.Generators.Emitters;

/// <summary>Emits internal singleton instances for valid result error mappers.</summary>
internal static class ResultErrorMapperCacheEmitter
{
  public const string HintName = "ResultErrorMapperCache.g.cs";

  public static string Emit(IReadOnlyList<MapperDescriptor> mapperDescriptors)
  {
    var source = new StringBuilder();
    source.AppendLine("// <auto-generated/>");
    source.AppendLine();
    source.AppendLine("#nullable enable");
    source.AppendLine();
    source.AppendLine("internal static class CSharpFunctionalExtensionsHttpResultsResultErrorMapperCache {");

    foreach (var mapper in mapperDescriptors.Where(info => !info.IsServiceMapper))
      source.AppendLine(
        $"    internal static {mapper.MapperInterfaceType} {mapper.CacheMemberName} {{ get; }} = new {mapper.FullyQualifiedName}();"
      );

    source.AppendLine("}");
    return source.ToString();
  }
}
